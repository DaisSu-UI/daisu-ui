export function translateDemo(text: string, locale: string): string {
  const messages = locale === 'en-US' ? demoEnglish : locale === 'zh-TW' ? demoTraditional : undefined;
  if (!messages) return text;
  if (messages[text] !== undefined) return messages[text];
  for (const [pattern, english, traditional] of patterns) {
    if (pattern.test(text)) return text.replace(pattern, locale === 'en-US' ? english : traditional);
  }
  return text;
}
